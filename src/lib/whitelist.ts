/**
 * Check if an email is on the whitelist.
 * Case-insensitive comparison, trims whitespace.
 */
export function isEmailWhitelisted(email: string): boolean {
  if (!email || typeof email !== 'string') return false;
  return WHITELIST_EMAILS.has(email.trim().toLowerCase());
}

/**
 * Get the total number of whitelisted emails (for admin info).
 */
export function getWhitelistCount(): number {
  return WHITELIST_EMAILS.size;
}
